def compare_symmetries(
    L: int = 6,
    t: float = 1.0,
    U_init: float = 2.0,
    U_final: float = 6.0,
    time: float = 0.5,
    dt: float = 0.05,
    scheme: str = '2s',
    order: int = 2,
    bond_dim: int = 64,
    expand_k: int = 4,
    expand_alpha: Optional[int] = None,
) -> None:
    """Run the same quench in all four symmetry groups and compare.

    No closed-form reference exists for an interacting quench, so this is the
    strongest available correctness statement: four different symmetry
    bookkeepings, two of them non-Abelian, must agree on every observable.

    Parameters
    ----------
    L:
        Chain length.
    t:
        Hopping amplitude.
    U_init:
        Interaction whose ground state starts the evolution.
    U_final:
        Interaction generating the evolution.
    time:
        Total evolution time.
    dt:
        Time step.
    scheme:
        TDVP update scheme, shared by all four runs.
    order:
        Integrator order.
    bond_dim:
        Maximum bond dimension in multiplets.
    expand_k:
        Complement directions added per bond per local update, for `'1sp'`.
    expand_alpha:
        Internal bond of the cheap factorization inside the expansion, for
        `'1sp'`. `None` keeps the full bond.
    """
    print(f"Symmetry-group comparison  (L = {L}, t = {t}, "
          f"U {U_init} -> {U_final}, t_final = {time}, dt = {dt}, "
          f"scheme = {scheme})")
    print()

    out = {}
    for symmetry in _SYMMETRIES:
        out[symmetry] = tdvp_hubbard_quench(
            L=L, t=t, U_init=U_init, U_final=U_final, symmetry=symmetry,
            time=time, dt=dt, scheme=scheme, order=order, bond_dim=bond_dim,
            expand_k=expand_k, expand_alpha=expand_alpha, verbose=False,
        )

    print(f"{'symmetry':>10}  {'<H(U_final)>':>15}  {'N':>12}  {'D':>12}  "
          f"{'|overlap|':>11}  {'mult':>5}  {'states':>6}")
    print('-' * 86)
    for symmetry in _SYMMETRIES:
        r = out[symmetry]
        print(f"{symmetry:>10}  {r['E']:>15.10f}  {r['N']:>12.8f}  "
              f"{r['D']:>12.8f}  {abs(r['overlap']):>11.8f}  "
              f"{max(r['mult']):>5d}  {max(r['states']):>6d}")

    ref = out[_SYMMETRIES[0]]
    print()
    print(f"Deviations from {_SYMMETRIES[0]}")
    print(f"{'symmetry':>10}  {'dE':>11}  {'dN':>11}  {'dD':>11}  "
          f"{'max dn_j':>11}  {'max dS':>11}")
    print('-' * 76)
    for symmetry in _SYMMETRIES[1:]:
        r = out[symmetry]
        print(f"{symmetry:>10}  {r['E'] - ref['E']:>+11.2e}  "
              f"{r['N'] - ref['N']:>+11.2e}  {r['D'] - ref['D']:>+11.2e}  "
              f"{np.max(np.abs(r['n_sites'] - ref['n_sites'])):>11.2e}  "
              f"{np.max(np.abs(r['S'] - ref['S'])):>11.2e}")
    print()
    print("Z2 conserves only fermion parity while U1 conserves particle")
    print("number, and the SU(2) groups resolve total spin rather than S_z, so")
    print("these four are genuinely different bookkeepings of one state.")
    print()
    print("The floor here is the initial state, not the evolution: each group")
    print("runs its own DMRG to a finite `e_tol`, so the four starting points")
    print("already differ at that level and TDVP merely carries the difference")
    print("along. Tightening `e_tol` tightens the whole table.")


