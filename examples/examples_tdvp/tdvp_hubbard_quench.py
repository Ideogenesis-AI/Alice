"""Example: TDVP interaction quench on the Hubbard chain, all four symmetries.

Finds the ground state of the Hubbard model at interaction `U_init` with DMRG,
then evolves it in real time under the *same* Hamiltonian with a different
interaction `U_final`:

    H(U) = -t Σ_{j,σ} (c†_{j,σ} c_{j+1,σ} + h.c.) + U Σ_j n_{j,↑} n_{j,↓}

    |ψ(0)⟩ = ground state of H(U_init),   |ψ(t)⟩ = exp(-i H(U_final) t) |ψ(0)⟩

The observable of interest is the double occupancy `D(t) = Σ_j ⟨n_{j↑} n_{j↓}⟩`,
which is the quantity the quench actually drives: the initial state is
optimized for `U_init`, so under `U_final` it is not stationary and `D`
relaxes and oscillates.

Why this example exists alongside `tdvp_hubbard.py`. That one starts from a
product state, which pins it to the `U1,*` groups, because under `Z2,*` the
even-parity sector merges |0⟩ with |↑↓⟩ into a single two-dimensional sector
and a site configuration can no longer name them apart. Here the initial state
comes from iterative diagonalization followed by DMRG instead, and a ground
state is reachable in every group — so this is the example that exercises all
four, `Z2,SU2` included.

There is no closed-form reference for an interacting quench, so correctness
rests on three things that do not require one:

1. **Energy conservation.** The evolution is generated by `H(U_final)`, so
   `⟨H(U_final)⟩` must not move, while `⟨H(U_init)⟩` generally does. Note that
   the conserved energy is *not* the DMRG ground-state energy unless
   `U_final == U_init`.
2. **The eigenstate limit.** With `--U-final` equal to `--U-init` the initial
   state *is* an eigenstate, so nothing should happen beyond a global phase:
   `|⟨ψ(0)|ψ(t)⟩| = 1` and the phase must wind as `exp(-i E t)`. This is the
   single sharpest check available here, and it is sensitive to the sign of
   the propagator, which conservation laws are not.
3. **Agreement across symmetry groups.** The four groups share no tensor
   structure — two carry intertwiners, two do not; two resolve `S_z`, two
   only total spin — yet must produce identical observables. `Z2` conserves
   only fermion parity rather than particle number, so the four are genuinely
   different bookkeeping, not relabelings.

All three update schemes run here, the ground state having open bonds for a
fixed-rank update to rotate within, and check 2 is what makes `--scheme 1sp`
worth running: the expansion widens a bond and then truncates it back, and an
eigenstate has to come through both untouched. An overlap that drifts below
one under `'1sp'` while `'1s'` and `'2s'` hold it at one is the expansion
losing part of the state — and nothing in checks 1 or 3 would report it.

A note on bond dimensions: under SU(2) a bond counts *multiplets*, so
`--bond-dim` means different things in different groups and the reports give
both the multiplet and the state-resolved counts. `MPS.bond_states` is the
latter.

DMRG runs in real arithmetic: its environments are built from a real identity
and it has no reason to be complex. `tdvp.run` promotes the state and the MPO
to `complex128` itself, so the handoff needs nothing from the caller.

Run from the repository root:

    uv run python examples/examples_tdvp/tdvp_hubbard_quench.py
    uv run python examples/examples_tdvp/tdvp_hubbard_quench.py --symmetry Z2,SU2
    uv run python examples/examples_tdvp/tdvp_hubbard_quench.py --U-init 0.0 --U-final 8.0
    uv run python examples/examples_tdvp/tdvp_hubbard_quench.py --eigenstate
    uv run python examples/examples_tdvp/tdvp_hubbard_quench.py --compare-symmetries
    uv run python examples/examples_tdvp/tdvp_hubbard_quench.py --L 8 --bond-dim 64
    uv run python examples/examples_tdvp/tdvp_hubbard_quench.py --scheme 1sp --expand-k 8
    uv run python examples/examples_tdvp/tdvp_hubbard_quench.py --help
"""

