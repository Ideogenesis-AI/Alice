def _hubbard_mpo(L: int, t: float, U: float, symmetry: str):
    """Build the Hubbard MPO and the on-site observables at a given `U`.

    Parameters
    ----------
    L:
        Chain length.
    t:
        Hopping amplitude.
    U:
        On-site Coulomb repulsion.
    symmetry:
        Band symmetry string.

    Returns
    -------
    tuple
        `(mpo, n_obs, d_obs)` with per-site occupation and double-occupancy
        MPOs.
    """
    cfg = {
        'geometry': {'lattice': 'chain', 'lx': L, 'bcx': 'OBC', 'n2x': True},
        'model': {
            'category': 'conductor',
            'label': 'Hubbard',
            'symmetry': symmetry,
            't': t,
            'U': U,
            'mu': 0.0,
        },
    }
    interactions, spc, geo = build_interaction(cfg)
    mpo = build_hamiltonian(interactions, geo.L, spc)
    _, ops = build_conductor(symmetry)
    return (mpo,
            occupation_mpos(geo.L, spc, ops),
            onsite_mpos(geo.L, spc, ops, key='NN4', name='NN'))


def _ground_state(
    L: int,
    t: float,
    U: float,
    symmetry: str,
    bond_dim: int,
    n_sweeps: int,
) -> Tuple[MPS, float]:
    """Find the Hubbard ground state at interaction `U` with DMRG.

    The starting point is the `U = 0` spinful chain from iterative
    diagonalization, which is a good guess at any `U` and, unlike a site
    configuration, is available in every symmetry group.

    Parameters
    ----------
    L:
        Chain length.
    t:
        Hopping amplitude.
    U:
        On-site Coulomb repulsion of the Hamiltonian to minimize.
    symmetry:
        Band symmetry string.
    bond_dim:
        Maximum bond dimension, in multiplets for the SU(2) groups.
    n_sweeps:
        Maximum number of DMRG sweeps.

    Returns
    -------
    MPS
        Ground-state MPS, real-valued, with `center == 0`.
    float
        Converged ground-state energy.
    """
    _, _, tensors = iter_diag_band(N=L, Nkeep=bond_dim, t=t,
                                   symmetry=symmetry, verbose=False)
    mps = MPS(tensors, center=None)
    mps.canonical(0)
    mps.normalize()

    mpo, _, _ = _hubbard_mpo(L, t, U, symmetry)
    summary = dmrg.run(mps, mpo, dmrg.Options(
        scheme='2s', n_sweeps=n_sweeps, max_bond=bond_dim, e_tol=1e-10))
    state = summary.state
    state.canonical(0)
    state.normalize()
    return state, summary.energy


