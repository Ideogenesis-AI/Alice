def tdvp_hubbard_quench(
    L: int = 6,
    t: float = 1.0,
    U_init: float = 2.0,
    U_final: float = 6.0,
    symmetry: str = 'U1,SU2',
    time: float = 1.0,
    dt: float = 0.025,
    scheme: str = '2s',
    order: int = 2,
    bond_dim: int = 64,
    n_sweeps: int = 12,
    trunc_thresh: float = 1e-12,
    expand_k: int = 4,
    expand_alpha: Optional[int] = None,
    krylov_dim: int = 16,
    snapshots: int = 5,
    checkpoint_dir: Optional[str] = None,
    env_cache_dir: Optional[str] = None,
    verbose: bool = True,
) -> dict:
    """Quench the Hubbard interaction and track the double occupancy.

    Parameters
    ----------
    L:
        Chain length.
    t:
        Nearest-neighbor hopping amplitude.
    U_init:
        Interaction of the Hamiltonian whose ground state starts the evolution.
    U_final:
        Interaction of the Hamiltonian that generates the evolution. Equal to
        `U_init` means no quench, which is the eigenstate-phase check.
    symmetry:
        Band symmetry, any of `'U1,U1'`, `'Z2,U1'`, `'U1,SU2'`, `'Z2,SU2'`.
    time:
        Total evolution time.
    dt:
        Time step.
    scheme:
        `'2s'` (default), `'1s'`, or `'1sp'`. The DMRG ground state already
        has open bonds, so `'1s'` is usable here unlike in a product-state
        quench, and `'1sp'` is free to spend its expansion on the rank the
        quench actually asks for rather than on opening bonds at all.
    order:
        Integrator order, `1` or `2`.
    bond_dim:
        Maximum bond dimension, in multiplets for the SU(2) groups.
    n_sweeps:
        Maximum number of DMRG sweeps for the initial ground state.
    trunc_thresh:
        SVD truncation threshold.
    expand_k:
        Complement directions added per bond per local update, for `'1sp'`.
        Counted in multiplets under the SU(2) groups, as `bond_dim` is.
    expand_alpha:
        Internal bond of the cheap factorization inside the expansion, for
        `'1sp'`. `None` keeps the full bond.
    krylov_dim:
        Maximum Krylov subspace dimension.
    snapshots:
        Number of intermediate times at which to report.
    checkpoint_dir:
        Directory for `tdvp.ckpt` and `evolution.ckpt`.
    env_cache_dir:
        Directory for spilling environment blocks to disk.
    verbose:
        Print the trajectory table and the final report.

    Returns
    -------
    dict
        Final observables, for the cross-symmetry comparison to diff.
    """
    if symmetry not in _SYMMETRIES:
        raise ValueError(f"symmetry must be one of {_SYMMETRIES}, "
                         f"got {symmetry!r}")

    phys, _ = build_conductor(symmetry)
    is_eigenstate = (U_final == U_init)

    # -----------------------------------------------------------------------
    # Ground state at U_init
    # -----------------------------------------------------------------------
    if verbose:
        print(f"Chain length   : {L}")
        print(f"Hopping t      : {t}")
        print(f"Quench         : U = {U_init}  ->  U = {U_final}"
              f"{'   (no quench: eigenstate-phase check)' if is_eigenstate else ''}")
        print(f"Symmetry       : {symmetry}"
              f"   ({'non-Abelian' if 'SU2' in symmetry else 'Abelian'}, "
              f"{'parity' if symmetry.startswith('Z2') else 'particle number'} "
              f"conserved)")
        print(f"Physical space : {phys.dim} multiplets / "
              f"{phys.num_states} states per site")
        print(f"Scheme         : {scheme}   order = {order}")
        if scheme in ('1sp', '1-site-plus', 'one-site-plus'):
            alpha_str = str(expand_alpha) if expand_alpha is not None else 'full'
            print(f"  expand_k     : {expand_k} multiplets"
                  f"   expand_alpha : {alpha_str}")
        print(f"Time step      : {dt}   total time = {time}")
        print(f"Bond dim       : {bond_dim} multiplets")
        print()

    state, e_init = _ground_state(L, t, U_init, symmetry, bond_dim, n_sweeps)
    mpo_init, _, _ = _hubbard_mpo(L, t, U_init, symmetry)
    mpo, n_obs, d_obs = _hubbard_mpo(L, t, U_final, symmetry)

    # The conserved quantity is the energy of the *evolving* Hamiltonian, which
    # differs from the DMRG ground-state energy whenever the quench is real.
    e_conserved = observe(state, mpo)

    # Snapshot the initial state for the overlap. Cloning tensor by tensor
    # rather than `copy.deepcopy`: a non-Abelian tensor carries intertwiners
    # holding a `CGSpec` that cannot be pickled, so deepcopy fails outright
    # under SU(2).
    reference = MPS([state[i].clone() for i in range(L)], center=state.center)
    reference.to(dtype=torch.complex128)

    if verbose:
        print(f"DMRG ground state at U = {U_init}")
        print(f"  energy <H(U_init)>  : {e_init:+.10f}")
        print(f"  energy <H(U_final)> : {e_conserved:+.10f}  "
              f"(this is what must stay fixed)")
        print(f"  bond multiplets     : {state.bond_dims}")
        print(f"  bond states         : {state.bond_states}")
        print(f"  double occupancy    : "
              f"{mps_occupations(state, d_obs).sum():.10f}")
        print()

    # -----------------------------------------------------------------------
    # Evolve under H(U_final)
    # -----------------------------------------------------------------------
    n_total = max(1, round(time / dt))
    stride = max(1, n_total // max(1, snapshots))

    opts = tdvp.Options(
        scheme=scheme,
        dt=dt,
        n_steps=n_total,
        order=order,
        max_bond=bond_dim,
        trunc_thresh=trunc_thresh,
        expand_k=expand_k,
        expand_alpha=expand_alpha,
        krylov_dim=krylov_dim,
        checkpoint_dir=checkpoint_dir,
        env_cache_dir=env_cache_dir,
        save_artifacts=False,
    )

    if verbose:
        print(f"{'t':>6}  {'D(t)':>12}  {'E drift':>10}  {'N':>12}  "
              f"{'|<psi0|psi>|':>12}  {'S_max':>9}  {'mult':>5}  {'states':>6}")
        print('-' * 88)

    artifact = tdvp.Artifact(state=state, time=0.0, step=0)
    summary = None
    step = 0
    while step < n_total:
        step = min(n_total, step + stride)
        summary, artifact = tdvp.run(artifact, mpo,
                                     dataclasses.replace(opts, n_steps=step))
        if verbose:
            print(f"{artifact.time:>6.3f}  "
                  f"{mps_occupations(artifact.state, d_obs).sum():>12.8f}  "
                  f"{observe(artifact.state, mpo) - e_conserved:>+10.2e}  "
                  f"{mps_occupations(artifact.state, n_obs).sum():>12.8f}  "
                  f"{abs(mps_overlap(reference, artifact.state)):>12.9f}  "
                  f"{max(mps_entropy(artifact.state, ell) for ell in range(1, L)):>9.6f}  "
                  f"{max(artifact.state.bond_dims):>5d}  "
                  f"{max(artifact.state.bond_states):>6d}")

    # -----------------------------------------------------------------------
    # Final report
    # -----------------------------------------------------------------------
    num = mps_occupations(artifact.state, n_obs)
    dbl = mps_occupations(artifact.state, d_obs)
    overlap = mps_overlap(reference, artifact.state)
    out = {
        'E': observe(artifact.state, mpo),
        'E_init_H': observe(artifact.state, mpo_init),
        'N': float(num.sum()),
        'D': float(dbl.sum()),
        'D_sites': dbl,
        'n_sites': num,
        'S': np.array([mps_entropy(artifact.state, ell) for ell in range(1, L)]),
        'overlap': overlap,
        'mult': artifact.state.bond_dims,
        'states': artifact.state.bond_states,
        'dw': max(summary.discarded_weights),
        'e_conserved': e_conserved,
        'e_init': e_init,
    }

    if verbose:
        print()
        print(f"Final state at t = {artifact.time:g}")
        print(f"  <H(U_final)>      : {out['E']:+.10f}  "
              f"(drift {out['E'] - e_conserved:+.2e})")
        print(f"  <H(U_init)>       : {out['E_init_H']:+.10f}  "
              f"(moved by {out['E_init_H'] - e_init:+.4e}; "
              f"{'expected, the quench is real' if not is_eigenstate else 'should be ~0'})")
        print(f"  particle number   : {out['N']:.10f}")
        print(f"  double occupancy  : {out['D']:.10f}  "
              f"(per site {', '.join(f'{v:.4f}' for v in dbl)})")
        print(f"  norm              : {artifact.state.norm():.12f}")
        print(f"  bond multiplets   : {out['mult']}")
        print(f"  bond states       : {out['states']}")
        print(f"  max discarded     : {out['dw']:.2e}")
        print()

        if is_eigenstate:
            # exp(-i H t)|E> = exp(-i E t)|E>: the magnitude pins the state,
            # the phase pins the sign convention of the propagator.
            expected = complex(math.cos(-e_conserved * artifact.time),
                               math.sin(-e_conserved * artifact.time))
            print("Eigenstate-phase check  (U_final == U_init)")
            print(f"  |<psi(0)|psi(t)>|   : {abs(overlap):.12f}  (exact 1)")
            print(f"  phase    measured   : {overlap.real:+.9f}{overlap.imag:+.9f}i")
            print(f"  phase    exp(-iEt)  : {expected.real:+.9f}{expected.imag:+.9f}i")
            print(f"  deviation           : {abs(overlap - expected):.3e}")
            print()
            print("  The magnitude says the state did not move off the")
            print("  eigenvector; the phase says the propagator is exp(-iHt)")
            print("  and not exp(+iHt), which no conservation law would catch.")
        else:
            print(f"Overlap with the initial state : {abs(overlap):.9f}")
            print("  Below one because the quench genuinely moved the state;")
            print("  a value of one would mean the evolution did nothing.")

    return out


