class TestIntegratorOrder:
    """The two orders differ in snapshot placement, not in the flow.

    Two `order=1` steps of `dt` apply exactly the same local exponentials, in
    the same sequence, as one `order=2` step of `2·dt`. That equivalence is
    the reason the docstring stops short of calling `order=2` more accurate.
    """

    def test_two_order_1_steps_equal_one_order_2_double_step(self, heisenberg_L6):
        from .conftest import mps_overlap

        mps_a, mpo = heisenberg_L6
        mps_a.canonical(0)
        mps_a.normalize()
        mps_b = copy.deepcopy(mps_a)

        env_left, env_right = _forward_envs(mps_a, mpo)
        time_step(mps_a, mpo, env_left, env_right, _opts(order=1, dt=0.05))
        time_step(mps_a, mpo, env_left, env_right, _opts(order=1, dt=0.05),
                  forward=False)

        env_left, env_right = _forward_envs(mps_b, mpo)
        time_step(mps_b, mpo, env_left, env_right, _opts(order=2, dt=0.10))

        assert abs(abs(mps_overlap(mps_a, mps_b)) - 1.0) < 1e-9
