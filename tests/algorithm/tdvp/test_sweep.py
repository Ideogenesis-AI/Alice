"""Tests for alice.algorithm.tdvp.sweep.

A sweep is where the local updates become a global integrator, so the
properties worth testing are the global ones: the orthogonality center must
end up where the next half-sweep expects it, the norm must survive, and the
energy must be conserved to far better than the integrator's truncation
error, since the time evolution is generated by `H` itself.
"""

from __future__ import annotations

import copy
from types import SimpleNamespace

import pytest

from alice.algorithm.tdvp.environ import (
    Environment,
    build_left_envs,
    build_right_envs,
    left_env_boundary,
    right_env_boundary,
)
from alice.algorithm.tdvp.sweep import backward_sweep, forward_sweep, time_step
from alice.network import observe

from .conftest import bond_profile


def _opts(**kwargs):
    """Build a minimal options object for the sweep functions."""
    base = {
        'scheme': '2s',
        'dt': 0.05,
        'order': 2,
        'max_bond': None,
        'trunc_thresh': 1e-12,
        'krylov_dim': 16,
        'krylov_tol': 1e-12,
        'expand_k': 4,
        'expand_alpha': None,
    }
    base.update(kwargs)
    return SimpleNamespace(**base)


def _forward_envs(mps, mpo):
    """Seed environments for a forward sweep from center 0."""
    env_left, env_right = Environment(mps.L), Environment(mps.L)
    env_left[0] = left_env_boundary(mps, mpo)
    build_right_envs(mps, mpo, env_right)
    return env_left, env_right


def _backward_envs(mps, mpo):
    """Seed environments for a backward sweep from center L-1."""
    env_left, env_right = Environment(mps.L), Environment(mps.L)
    env_right[mps.L - 1] = right_env_boundary(mps, mpo)
    build_left_envs(mps, mpo, env_left)
    return env_left, env_right


# ---------------------------------------------------------------------------
# Half sweeps
# ---------------------------------------------------------------------------

@pytest.mark.parametrize('scheme', ['1s', '2s', '1sp'])
class TestHalfSweeps:
    """Tests for a single forward or backward half-sweep."""

    def test_forward_moves_the_center_to_the_far_end(self, heisenberg_L6, scheme):
        mps, mpo = heisenberg_L6
        mps.canonical(0)
        mps.normalize()
        env_left, env_right = _forward_envs(mps, mpo)
        forward_sweep(mps, mpo, env_left, env_right, _opts(scheme=scheme), 0.05)
        assert mps.center == mps.L - 1

    def test_backward_returns_the_center_to_the_origin(self, heisenberg_L6, scheme):
        mps, mpo = heisenberg_L6
        mps.canonical(mps.L - 1)
        mps.normalize()
        env_left, env_right = _backward_envs(mps, mpo)
        backward_sweep(mps, mpo, env_left, env_right, _opts(scheme=scheme), 0.05)
        assert mps.center == 0

    def test_forward_preserves_the_norm(self, heisenberg_L6, scheme):
        mps, mpo = heisenberg_L6
        mps.canonical(0)
        mps.normalize()
        env_left, env_right = _forward_envs(mps, mpo)
        forward_sweep(mps, mpo, env_left, env_right, _opts(scheme=scheme), 0.05)
        assert abs(mps.norm() - 1.0) < 1e-11

    def test_forward_rejects_a_misplaced_center(self, heisenberg_L6, scheme):
        """A forward sweep from the wrong end is a caller bug, not a no-op."""
        mps, mpo = heisenberg_L6
        mps.canonical(mps.L - 1)
        env_left, env_right = _backward_envs(mps, mpo)
        with pytest.raises(ValueError):
            forward_sweep(mps, mpo, env_left, env_right, _opts(scheme=scheme), 0.05)

    def test_backward_rejects_a_misplaced_center(self, heisenberg_L6, scheme):
        mps, mpo = heisenberg_L6
        mps.canonical(0)
        env_left, env_right = _forward_envs(mps, mpo)
        with pytest.raises(ValueError):
            backward_sweep(mps, mpo, env_left, env_right, _opts(scheme=scheme), 0.05)


